#!/usr/bin/env python3
"""Subset Inter (SIL OFL 1.1) to the characters the UI needs, convert the CFF
outlines to TrueType quadratics (most robust path for stb_truetype), map the
digits to Inter's tabular figures (steady numbers while dragging sliders) and
embed the result as C++ byte arrays in src/font_data.h."""
import io, os, sys
from fontTools.ttLib import TTFont, newTable
from fontTools import subset
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.ttGlyphPen import TTGlyphPen

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_DIR = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/opentype/inter'
FACES = [('Regular', 'Inter-Regular.otf'), ('Medium', 'Inter-Medium.otf'),
         ('SemiBold', 'Inter-SemiBold.otf'), ('Bold', 'Inter-Bold.otf')]
UNICODES = list(range(0x20, 0x7F)) + [0xA0, 0xA9, 0xB0, 0xB1, 0xB7, 0xD7, 0x2013, 0x2014, 0x2018,
            0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2190, 0x2191, 0x2192, 0x2193, 0x21BB,
            0x21E7, 0x2318, 0x2713, 0x25CF, 0x25C6, 0x2715]

def tnum_map(font):
    m = {}
    gsub = font['GSUB'].table
    for fr in gsub.FeatureList.FeatureRecord:
        if fr.FeatureTag != 'tnum':
            continue
        for li in fr.Feature.LookupListIndex:
            lk = gsub.LookupList.Lookup[li]
            for st in lk.SubTable:
                if lk.LookupType == 7:
                    st = st.ExtSubTable
                if hasattr(st, 'mapping'):
                    m.update(st.mapping)
    return m

def otf_to_ttf(font):
    glyphOrder = font.getGlyphOrder()
    glyphSet = font.getGlyphSet()
    glyf = newTable('glyf'); glyf.glyphOrder = glyphOrder; glyf.glyphs = {}
    for name in glyphOrder:
        pen = TTGlyphPen(glyphSet)
        glyphSet[name].draw(Cu2QuPen(pen, max_err=0.6, reverse_direction=True))
        glyf.glyphs[name] = pen.glyph()
    font['loca'] = newTable('loca')
    font['glyf'] = glyf
    del font['CFF ']
    if 'VORG' in font: del font['VORG']
    maxp = font['maxp']; maxp.tableVersion = 0x00010000
    for attr in ('maxZones', 'maxTwilightPoints', 'maxStorage', 'maxFunctionDefs', 'maxInstructionDefs',
                 'maxStackElements', 'maxSizeOfInstructions', 'maxComponentElements'):
        setattr(maxp, attr, 0)
    maxp.maxZones = 1
    font['head'].indexToLocFormat = 0; font['head'].glyphDataFormat = 0
    post = font['post']; post.formatType = 2.0; post.extraNames = []; post.mapping = {}
    post.glyphOrder = glyphOrder
    font.sfntVersion = '\x00\x01\x00\x00'

def build(face, fname):
    font = TTFont(os.path.join(SRC_DIR, fname))
    tn = tnum_map(font)
    cmap = font.getBestCmap()
    # remap digits to tabular figures before subsetting so the tabular glyphs are kept
    for t in font['cmap'].tables:
        if t.isUnicode():
            for cp in range(0x30, 0x3A):
                g = t.cmap.get(cp)
                if g in tn:
                    t.cmap[cp] = tn[g]
    opts = subset.Options()
    opts.layout_features = ['kern']
    opts.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
    opts.name_legacy = True; opts.name_languages = ['*']
    opts.notdef_outline = True; opts.glyph_names = True
    opts.hinting = False; opts.desubroutinize = True
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=UNICODES)
    sub.subset(font)
    otf_to_ttf(font)
    buf = io.BytesIO(); font.save(buf)
    data = buf.getvalue()
    out = os.path.join(ROOT, 'assets', 'fonts', 'Inter-%s-subset.ttf' % face)
    open(out, 'wb').write(data)
    print(face, len(data), 'bytes')
    return data

def main():
    blobs = [(face, build(face, f)) for face, f in FACES]
    lines = ['// Generated by tools/make_fonts.py - Inter (c) The Inter Project Authors, SIL Open Font License 1.1',
             '#pragma once', '#include <cstddef>', '#include <cstdint>', 'namespace vx { namespace fontdata {']
    for face, data in blobs:
        lines.append('alignas(4) static const uint8_t k%s[%d] = {' % (face, len(data)))
        for i in range(0, len(data), 24):
            lines.append('  ' + ','.join(str(b) for b in data[i:i+24]) + ',')
        lines.append('};')
    lines.append('}}  // namespace vx::fontdata')
    open(os.path.join(ROOT, 'src', 'font_data.h'), 'w').write('\n'.join(lines) + '\n')
    print('wrote src/font_data.h')

main()
